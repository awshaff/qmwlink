"""High-precision mpmath references for noncentral chi-square (test oracle only)."""

from __future__ import annotations

import mpmath as mp


def _p_lower(a: mp.mpf, y: mp.mpf) -> mp.mpf:
    """Regularized lower incomplete gamma P(a, y) = y^a e^-y / Gamma(a+1) * sum_k y^k/(a+1)_k.

    A plain positive-term series (no cancellation); ``mp.gammainc`` gives up at a ~ 1e7 and
    ``mp.hyp1f1`` loses ~1e-8 relative accuracy in the lower tail at a ~ 1e5, so neither is used.
    """
    pref = mp.exp(a * mp.log(y) - y - mp.loggamma(a + 1))
    term = mp.mpf(1)
    total = mp.mpf(1)
    k = 0
    eps = mp.mpf(10) ** (-(mp.mp.dps + 5))
    while True:
        k += 1
        term = term * y / (a + k)
        total += term
        if k > y - a and term < eps * total:
            break
    return pref * total


def ncx2_cdf_mp(x: float, nu: float, lam: float, *, width: float = 11.0, dps: int = 30) -> mp.mpf:
    """CDF of chi'^2(nu, lam) as a Poisson mixture of central chi^2 cdfs.

    ``F = sum_j Pois(j; lam/2) P(nu/2 + j, x/2)`` over ``mu +/- width*sqrt(mu)``, with the
    regularized gamma terms generated by the *stable downward* recurrence
    ``P(a-1, y) = P(a, y) + t(a-1)`` anchored by one direct ``mp.gammainc``.
    """
    with mp.workdps(dps):
        y = mp.mpf(x) / 2
        mu = mp.mpf(lam) / 2
        a0 = mp.mpf(nu) / 2
        if mu == 0:
            return _p_lower(a0, y)
        half = int(width * mp.sqrt(mu)) + 10
        j_hi = int(mu) + half
        j_lo = max(0, int(mu) - half)
        a = a0 + j_hi
        p = _p_lower(a, y)
        # t(a) = y^a e^-y / Gamma(a+1) so that P(a+1) = P(a) - t(a)  =>  P(a-1) = P(a) + t(a-1)
        t_prev = mp.exp((a - 1) * mp.log(y) - y - mp.loggamma(a))  # t(a-1)
        w = mp.exp(-mu + j_hi * mp.log(mu) - mp.loggamma(j_hi + 1))
        total = w * p
        for j in range(j_hi, j_lo, -1):
            p = p + t_prev  # now P(a_j - 1)
            w = w * j / mu  # Pois(j-1) = Pois(j) * j / mu
            total += w * p
            a_prev = a0 + j - 1
            t_prev = t_prev * a_prev / y  # t(a_prev - 1) = t(a_prev) * a_prev / y
        return +total
